/*
 * guard.c - Guard runtime library.
 *
 * Every function below is a stub. Implement them in Part 1.
 */
#include "guard.h"

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>

#include <sys/mman.h>
#include <unistd.h>

/* Linker symbols: start of the executable and end of its code. */
extern char __executable_start[], _etext[];

static uintptr_t text_lo;    /* text segment: [text_lo, text_hi) */
static uintptr_t text_hi;
static uint8_t  *bitmap;     /* one bit per 16-byte slot */
static size_t    bitmap_len; /* in bytes */
static int       sealed;     /* set by guard_seal() */

__attribute__((constructor)) static void guard_init(void)
{
    text_lo = (uintptr_t)__executable_start;
    text_hi = (uintptr_t)_etext;

    size_t slots = (text_hi - text_lo + 15) / 16; /* round up */
    bitmap_len   = (slots + 7) / 8;              /* round up */

    /* Anonymous memory starts zeroed: no valid targets yet. */
    void *p = mmap(NULL, bitmap_len, PROT_READ | PROT_WRITE,
                   MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (p == MAP_FAILED) {
        perror("guard: mmap");
        abort();
    }
    bitmap = p;
}

void guard_register(void *fn)
{
    uintptr_t addr = (uintptr_t)fn;

    if (sealed) {
        fprintf(stderr, "guard: guard_register(%p) after guard_seal()\n", fn);
        abort();
    }
    /* Outside the text segment the index would fall outside the bitmap. */
    if (addr < text_lo || addr >= text_hi) {
        fprintf(stderr, "guard: guard_register(%p) outside text segment\n", fn);
        abort();
    }
    /* guard_is_valid() rejects unaligned addresses, so registering one
     * would silently cause a false positive later. */
    if (addr % 16 != 0) {
        fprintf(stderr, "guard: guard_register(%p) not 16-byte aligned\n", fn);
        abort();
    }

    size_t slot = (addr - text_lo) / 16;
    bitmap[slot / 8] |= (uint8_t)(1u << (slot % 8));
}

void guard_seal(void)
{
    if (mprotect(bitmap, bitmap_len, PROT_READ) != 0) {
        perror("guard: mprotect");
        abort();
    }
    sealed = 1;
}

int guard_is_valid(const void *addr)
{
    uintptr_t a = (uintptr_t)addr;

    if (a < text_lo || a >= text_hi)
        return 0;

    size_t slot = (a - text_lo) / 16;
    if (!(bitmap[slot / 8] & (1u << (slot % 8))))
        return 0;

    /* Hit: only the start of the slot is a function entry. */
    return a % 16 == 0;
}

_Noreturn void guard_violation(const char *what, const void *addr,
                               const char *file, int line)
{
    fprintf(stderr, "guard: %s violation at %s:%d (target %p)\n", what, file, line, addr);
    abort();
}

/* ------------------------------------------------------------------ */
/* Shadow stack                                                       */
/* ------------------------------------------------------------------ */

/* Usable size of the shadow stack: 1 MiB, i.e. 131072 return addresses. */
#define SS_SIZE ((size_t)1 << 20)

/*
 * Layout of the mapping (the stack grows upward):
 *
 *   +----------------+---------------------------+----------------+
 *   | guard page     | shadow stack              | guard page     |
 *   | PROT_NONE      | SS_SIZE bytes, read/write | PROT_NONE      |
 *   +----------------+---------------------------+----------------+
 *   ^ map            ^ base                      ^ limit
 *
 * top points to the next free slot:
 *   - empty when top == base
 *   - full  when top == limit
 */
struct shadow_stack {
    void  **base;    /* first usable slot (just above the lower guard page) */
    void  **top;     /* next free slot */
    void  **limit;   /* one past the last usable slot */
    char   *map;     /* start of the mapping, including guard pages */
    size_t  map_len; /* length of the mapping, for munmap */
};

static struct shadow_stack ss;

/*
 * Allocate the shadow stack.
 *
 * Priority 101 is the earliest one available to user code (0-100 are
 * reserved), so this runs before every constructor without a priority.
 * That includes the registration constructors generated by guardcc,
 * which are instrumented themselves and already use the shadow stack.
 */
__attribute__((constructor(101))) static void guard_ss_init(void)
{
    long pg = sysconf(_SC_PAGESIZE);
    if (pg <= 0) {
        perror("guard: sysconf(_SC_PAGESIZE)");
        abort();
    }

    size_t page = (size_t)pg;
    size_t len  = SS_SIZE + 2 * page;

    /*
     * Map the whole range as PROT_NONE first and then make only the
     * middle part read/write. This guarantees that the guard pages lie
     * directly against the stack.
     *
     * MAP_PRIVATE makes the mapping copy-on-write across fork(): the
     * child gets its own copy instead of sharing the parent's stack.
     */
    char *m = mmap(NULL, len, PROT_NONE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (m == MAP_FAILED) {
        perror("guard: mmap shadow stack");
        abort();
    }
    if (mprotect(m + page, SS_SIZE, PROT_READ | PROT_WRITE) != 0) {
        perror("guard: mprotect shadow stack");
        abort();
    }

    ss.map     = m;
    ss.map_len = len;
    ss.base    = (void **)(m + page);
    ss.top     = ss.base;
    ss.limit   = (void **)(m + page + SS_SIZE);
}

/* Report a shadow stack error (overflow, underflow or return address
 * mismatch) on stderr and abort(). Never returns. */
_Noreturn void guard_ss_violation(const char *what, const void *addr,
                                  const char *file, int line)
{
    fprintf(stderr, "guard: shadow stack %s at %s:%d (return address %p)\n",
            what, file, line, addr);
    abort();
}

void guard_ss_push(void *ret, const char *file, int line)
{
    if (ss.top == ss.limit)
        guard_ss_violation("overflow", ret, file, line);

    *ss.top++ = ret;
}

void guard_ss_check_pop(void *ret, const char *file, int line)
{
    if (ss.top == ss.base)
        guard_ss_violation("underflow", ret, file, line);

    void *expected = *--ss.top;

    if ((uintptr_t)expected != (uintptr_t)ret)
        guard_ss_violation("return address mismatch", ret, file, line);
}
